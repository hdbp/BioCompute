#!/usr/bin/env python3
"""Generate a small SYNTHETIC paired-end FASTQ dataset for testing BioCompute.

These reads are random sequences with condition-specific GC content and quality
profiles. They are NOT biological data and must not be used for scientific conclusions.

usage: generate_test_data.py OUTDIR [--reads N] [--seed S]
"""
import argparse
import gzip
import os
import random

SAMPLES = [
    # (file stem, condition, replicate, gc, mean_q, lanes)
    ("CTRL_rep1_S1", "control", 1, 0.42, 34, 1),
    ("CTRL_rep2_S2", "control", 2, 0.43, 33, 1),
    ("TREAT_rep1_S3", "treated", 1, 0.51, 31, 2),   # split across two lanes
    ("TREAT_rep2_S4", "treated", 2, 0.50, 24, 1),   # deliberately lower quality
    ("INPUT_S5", "input", 1, 0.41, 33, 1),
]


def read(rng, n, gc, mq, length):
    seq = "".join(rng.choice("GC") if rng.random() < gc else rng.choice("AT") for _ in range(length))
    qual = "".join(chr(33 + max(2, min(41, int(rng.gauss(mq, 5))))) for _ in range(length))
    return seq, qual


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("outdir")
    ap.add_argument("--reads", type=int, default=2000)
    ap.add_argument("--seed", type=int, default=7)
    a = ap.parse_args()
    os.makedirs(a.outdir, exist_ok=True)
    rng = random.Random(a.seed)
    meta = ["sample_id\tcondition\treplicate\tbatch\tantibody\tnotes"]
    for stem, cond, rep, gc, mq, lanes in SAMPLES:
        for lane in range(1, lanes + 1):
            for r in (1, 2):
                path = os.path.join(a.outdir, f"{stem}_L00{lane}_R{r}_001.fastq.gz")
                with gzip.open(path, "wt", compresslevel=1) as fh:
                    for i in range(a.reads):
                        length = rng.choice([100, 100, 100, 98, 76, 45])
                        s, q = read(rng, i, gc, mq, length)
                        fh.write(f"@SYN:{stem}:{lane}:{i} {r}:N:0:SYNTHETIC\n{s}\n+\n{q}\n")
        name = stem.rsplit("_S", 1)[0]
        meta.append(f"{name}\t{cond}\t{rep}\tbatch{1 if rep == 1 else 2}\t{'H3K27ac' if cond != 'input' else ''}\tsynthetic")
    with open(os.path.join(a.outdir, "sample_metadata.tsv"), "w") as fh:
        fh.write("\n".join(meta) + "\n")
    with open(os.path.join(a.outdir, "README.txt"), "w") as fh:
        fh.write("SYNTHETIC test reads generated by BioCompute examples/data/generate_test_data.py.\n"
                 "Not biological data. Safe to delete.\n")
    print(f"wrote synthetic dataset to {a.outdir}")


if __name__ == "__main__":
    main()
