"""Engine adapters: translate a Run into a concrete, shell-free command line.

Each adapter knows how to (1) run preflight checks, (2) build the argv/env for the
detached wrapper, (3) render engine-specific resource configuration. Progress parsing
is shared because both engines emit a Nextflow-format ``trace.txt`` and
``Submitted process > NAME`` log lines.
"""
from __future__ import annotations

import csv
import json
import os
import re
import shutil
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from ..config import get_settings
from ..services import tools

BCFLOW = Path(__file__).with_name("bcflow.py")


@dataclass
class Check:
    name: str
    ok: bool
    detail: str = ""
    level: str = "error"  # error | warning | info

    def as_dict(self) -> dict[str, Any]:
        return {"name": self.name, "ok": self.ok, "detail": self.detail, "level": self.level}


@dataclass
class LaunchSpec:
    argv: list[str]
    env: dict[str, str] = field(default_factory=dict)
    cwd: str = "."


def _groovy_str(s: str) -> str:
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"


class NextflowAdapter:
    name = "nextflow"

    def preflight(self, pipeline_path: Path, resources: dict[str, Any]) -> list[Check]:
        s = get_settings()
        checks: list[Check] = []
        nf = tools.nextflow_status()
        checks.append(Check("Nextflow executable", nf["available"], nf.get("detail", "")))
        java = tools.inventory().get("java")
        checks.append(Check("Java runtime", bool(java), f"java {java}" if java else f"'{s.java_bin}' not found"))
        checks.append(Check("Pipeline entry point", (pipeline_path / "main.nf").is_file(), str(pipeline_path / "main.nf")))
        prof = resources.get("profile") or ""
        for p in [x for x in prof.split(",") if x]:
            if p in ("docker",):
                ok = bool(tools.inventory().get("docker"))
                checks.append(Check(f"Profile '{p}' runtime", ok, "docker available" if ok else "docker not found"))
            if p in ("singularity", "apptainer"):
                inv = tools.inventory()
                ok = bool(inv.get("apptainer") or inv.get("singularity"))
                checks.append(Check(f"Profile '{p}' runtime", ok, "apptainer/singularity available" if ok else "not found"))
            if p in ("conda", "mamba"):
                ok = bool(tools.inventory().get("conda") or tools.inventory().get("mamba"))
                checks.append(Check(f"Profile '{p}' runtime", ok, "conda available" if ok else "conda not found"))
        if resources.get("executor") == "condor":
            ok = bool(tools.inventory().get("htcondor"))
            checks.append(Check("HTCondor submit tools", ok, "condor_submit available" if ok else
                                "HTCondor is not installed on the controller"))
            checks.append(Check("Shared work directory", True,
                                "Nextflow's condor executor requires the work directory to be on a filesystem "
                                "shared by all selected execution nodes", level="warning"))
        return checks

    def config(self, resources: dict[str, Any], run_dir: Path) -> str:
        """biocompute.config - layered on top of the pipeline's own config with -c."""
        cpus = int(resources.get("max_cpus") or os.cpu_count() or 1)
        mem = float(resources.get("max_memory_gb") or 4)
        lines = ["// Generated by BioCompute - scheduler resource limits for this run",
                 f"// Run directory: {run_dir}", ""]
        if resources.get("executor") == "condor":
            hosts = resources.get("nodes") or []
            req = " || ".join(f'(Machine == "{h}")' for h in hosts if re.fullmatch(r"[\w.-]+", h))
            lines += ["process {", "    executor = 'condor'"]
            if req:
                lines.append(f"    clusterOptions = {_groovy_str('requirements = ' + req)}")
            lines += ["}", f"executor {{ name = 'condor'; queueSize = {int(resources.get('queue_size') or 100)} }}"]
        else:
            lines += ["executor {", "    name = 'local'", f"    cpus = {cpus}", f"    memory = '{mem:g} GB'", "}"]
        # nf-core resourceLimits (Nextflow >= 24.04) caps individual process requests
        lines += ["process {", f"    resourceLimits = [ cpus: {cpus}, memory: '{mem:g} GB', time: '{int(resources.get('max_time_h') or 240)}h' ]", "}"]
        # a resumed run writes its report and timeline again: without overwrite Nextflow stops with "file already exists"
        lines += ["report { overwrite = true }", "timeline { overwrite = true }"]
        if cleanup_wanted(resources):
            # intermediate files in the work folder are deleted when the run succeeds (a failed run keeps them for -resume)
            lines += ["cleanup = true"]
        lines += ["trace {", "    enabled = true", "    overwrite = true",
                  "    fields = 'task_id,hash,native_id,process,tag,name,status,exit,submit,start,complete,duration,realtime,%cpu,peak_rss,workdir'",
                  "}"]
        return "\n".join(lines) + "\n"

    def launch(self, *, pipeline_path: Path, run_dir: Path, work_dir: Path, params_file: Path,
               resources: dict[str, Any], session_name: str, resume_session: str | None) -> LaunchSpec:
        s = get_settings()
        cfg = run_dir / "biocompute.config"
        cfg.write_text(self.config(resources, run_dir))
        argv = [tools.nextflow_status().get("path") or s.nextflow_bin, "-log", str(run_dir / "nextflow.log"),
                "run", str(pipeline_path), "-name", session_name, "-params-file", str(params_file),
                "-work-dir", str(work_dir), "-c", str(cfg), "-with-trace", str(run_dir / "trace.txt"),
                "-with-report", str(run_dir / "report.html"), "-with-timeline", str(run_dir / "timeline.html"),
                "-ansi-log", "false"]
        if resources.get("profile"):
            prof = ",".join(p for p in str(resources["profile"]).split(",") if re.fullmatch(r"[\w-]+", p))
            if prof:
                argv += ["-profile", prof]
        if resume_session:
            # plain -resume continues the last session of this run folder; naming an earlier attempt fails when
            # that attempt never got as far as creating a Nextflow session
            argv += ["-resume"]
        env = {"NXF_ANSI_LOG": "false", "NXF_OPTS": f"-Xms256m -Xmx{int(resources.get('controller_heap_gb') or 4)}g"}
        if s.nextflow_home:
            env["NXF_HOME"] = str(s.nextflow_home)
        return LaunchSpec(argv=argv, env=env, cwd=str(run_dir))


def cleanup_wanted(resources: dict[str, Any]) -> bool:
    """Delete intermediate files of this run once they are no longer needed (unless the run asked to keep them)."""
    return get_settings().cleanup_intermediates and not resources.get("keep_work")


class BcflowAdapter:
    name = "bcflow"

    def preflight(self, pipeline_path: Path, resources: dict[str, Any]) -> list[Check]:
        checks = [Check("bcflow manifest", (pipeline_path / "bcflow.json").is_file(), str(pipeline_path / "bcflow.json"))]
        try:
            man = json.loads((pipeline_path / "bcflow.json").read_text())
            for req in man.get("requires", []):
                ok = shutil.which(req) is not None
                checks.append(Check(f"Tool '{req}'", ok, shutil.which(req) or "not found on PATH"))
        except (OSError, json.JSONDecodeError) as exc:
            checks.append(Check("bcflow manifest parse", False, str(exc)))
        if resources.get("executor") == "condor":
            checks.append(Check("Executor", False, "bcflow runs locally only; choose the Nextflow engine for HTCondor"))
        checks.append(Check("Engine", True, "BioCompute native engine: local execution, no containers", level="info"))
        return checks

    def launch(self, *, pipeline_path: Path, run_dir: Path, work_dir: Path, params_file: Path,
               resources: dict[str, Any], session_name: str, resume_session: str | None) -> LaunchSpec:
        params = json.loads(params_file.read_text())
        argv = [sys.executable, str(BCFLOW), "--manifest", str(pipeline_path / "bcflow.json"),
                "--params", str(params_file), "--outdir", params["outdir"], "--workdir", str(work_dir),
                "--trace", str(run_dir / "trace.txt"), "--max-cpus", str(int(resources.get("max_cpus") or 1))]
        if params.get("input"):
            argv += ["--samplesheet", params["input"]]
        if resume_session:
            argv.append("--resume")
        if cleanup_wanted(resources):
            argv.append("--cleanup")  # each task's folder goes as soon as nothing needs it any more
        return LaunchSpec(argv=argv, env={}, cwd=str(run_dir))


