# --------------------------------------------------------------------------- progress
SUBMIT_RE = re.compile(r"\[([0-9a-f]{2}/[0-9a-f]{6})\] (Submitted|Cached) process > (\S+)(?: \((.*)\))?")


def parse_progress(run_dir: Path) -> dict[str, Any]:
    """Process-level progress from trace.txt + stdout submissions (both engines)."""
    procs: dict[str, dict[str, int]] = {}
    tasks: dict[str, dict[str, Any]] = {}

    def bucket(name: str) -> dict[str, int]:
        return procs.setdefault(name, {"submitted": 0, "completed": 0, "cached": 0, "failed": 0, "running": 0})

    log = run_dir / "stdout.log"
    if log.exists():
        with open(log, errors="replace") as fh:
            for line in fh:
                m = SUBMIT_RE.search(line)
                if m:
                    h, kind, proc, tag = m.groups()
                    tasks[h] = {"hash": h, "process": proc, "tag": tag, "status": "CACHED" if kind == "Cached" else "SUBMITTED"}
    trace = run_dir / "trace.txt"
    rows: list[dict[str, str]] = []
    if trace.exists():
        with open(trace, newline="", errors="replace") as fh:
            rows = list(csv.DictReader(fh, delimiter="\t"))
    for r in rows:
        h = r.get("hash") or r.get("task_id")
        tasks[h] = {**tasks.get(h, {}), "hash": h, "process": r.get("process") or r.get("name", "").split(" (")[0],
                    "tag": r.get("tag"), "status": r.get("status"), "exit": r.get("exit"),
                    "duration": r.get("duration"), "realtime": r.get("realtime"), "cpu": r.get("%cpu"),
                    "peak_rss": r.get("peak_rss"), "workdir": r.get("workdir")}
    for t in tasks.values():
        b = bucket(t["process"])
        b["submitted"] += 1
        st = (t.get("status") or "").upper()
        if st == "COMPLETED":
            b["completed"] += 1
        elif st == "CACHED":
            b["cached"] += 1
        elif st in ("FAILED", "ABORTED"):
            b["failed"] += 1
        else:
            b["running"] += 1
    total = len(tasks)
    done = sum(1 for t in tasks.values() if (t.get("status") or "").upper() in ("COMPLETED", "CACHED"))
    return {"processes": procs, "tasks": list(tasks.values())[-500:], "total": total, "done": done,
            "failed": sum(1 for t in tasks.values() if (t.get("status") or "").upper() == "FAILED")}
